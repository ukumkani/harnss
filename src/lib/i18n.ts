const UI_PHRASE_ZH_CN = Object.entries(UI_TEXT_ZH_CN).sort((a, b) => b[0].length - a[0].length);

export function isAppLanguage(value: string): value is AppLanguage {
  return value === "en" || value === "zh-CN";
}

export function t(language: AppLanguage | undefined, key: TranslationKey): string {
  return TRANSLATIONS[language ?? DEFAULT_LANGUAGE]?.[key] ?? EN[key];
}

export function translateUiText(language: AppLanguage | undefined, text: string): string {
  if (language !== "zh-CN") return text;
  const exact = UI_TEXT_ZH_CN[text];
  if (exact != null) return exact;

  let translated = text;
  for (const [source, target] of UI_PHRASE_ZH_CN) {
    if (source.length < 3 || !translated.includes(source)) continue;
    translated = translated.split(source).join(target);
  }
  return translated;
}
